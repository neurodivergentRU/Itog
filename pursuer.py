"""
================================================================================
Модуль pursuer.py — Модель преследователя (метод Artificial Potential Fields)
================================================================================

Описание:
    Модуль реализует поведение преследователя на основе метода виртуальных
    потенциальных полей (Artificial Potential Fields, APF).

    Основная идея метода APF:
        — Цель (target) создаёт ПРИТЯГИВАЮЩИЙ потенциал: преследователь
          «скатывается» в направлении цели, как шарик по склону.
        — Препятствия (obstacles) создают ОТТАЛКИВАЮЩИЙ потенциал:
          преследователь «отталкивается» от препятствий.

    Математическая формулировка:
        ─────────────────────────────────────────────────────────────────
        1) Притягивающий потенциал (цель):

            U_att(q) = (1/2) · k_att · ρ²(q, q_goal)

            где ρ(q, q_goal) = ||q_goal − q|| — расстояние до цели.

        2) Притягивающая сила (отрицательный градиент):

            F_att = −∇U_att = k_att · (q_goal − q)

           При ρ > d_max ограничиваем силу (конусный потенциал):

            F_att = k_att · d_max · (q_goal − q) / ρ

        ─────────────────────────────────────────────────────────────────
        3) Отталкивающий потенциал (препятствие), классический FIRAS:

            U_rep(q) = (1/2) · k_rep · (1/ρ − 1/ρ₀)²,  если ρ ≤ ρ₀
            U_rep(q) = 0,                                  если ρ > ρ₀

            Классический градиент даёт силу  ~ 1/ρ³, которая ничтожно
            мала на границе зоны (ρ ≈ ρ₀) и взрывается у поверхности.
            На практике это означает, что преследователь «не замечает»
            зону влияния и огибает препятствие в последний момент.

        4) Модифицированная отталкивающая сила (практический APF):

            F_rep = k_rep · max(0, 1 − ρ/ρ₀) · (n̂ + α · t̂)

            где ρ  — расстояние от поверхности препятствия,
                  ρ₀ — радиус зоны влияния (d0),
                  n̂  — единичный вектор от препятствия к преследователю,
                  t̂  — тангенциальный вектор (перпендикуляр к n̂,
                        направленный в сторону цели),
                  α  — коэффициент тангенциальной силы (0.5).

            Свойства (линейная огибающая — значительна по всей зоне):
              • при ρ = 0    (поверхность): F_rep = k_rep (максимум)
              • при ρ = ρ₀/2 (середина):    F_rep = k_rep / 2
              • при ρ = ρ₀   (граница):     F_rep = 0  (плавно)

            Тангенциальная составляющая (α·t̂) обеспечивает «скольжение»
            вокруг препятствия в сторону цели, предотвращая «упирание»
            при лобовом подходе.

        ─────────────────────────────────────────────────────────────────
        5) Суммарная сила:

            F_total = F_att + Σ F_rep_i

        6) Движение преследователя:

            v = speed · F_total / ||F_total||

            (движение с постоянной скоростью в направлении суммарной силы)

        ─────────────────────────────────────────────────────────────────

    Также реализован упрощённый метод — «Прямое преследование» (Pure Pursuit):
        Преследователь всегда движется по прямой к текущей позиции цели,
        игнорируя препятствия.

Автор: Курсовая работа по дисциплине «Методы ИИ для беспилотных систем»
================================================================================
"""

import math


class Pursuer:
    """
    Класс преследователя — реализует метод преследования цели.

    Поддерживаемые методы:
        — APF (Artificial Potential Fields) — основной метод по варианту.
        — Pure Pursuit (Прямое преследование) — дополнительный метод.

    Атрибуты:
        x, y          (float) : текущие координаты (пиксели)
        x0, y0        (float) : начальные координаты
        speed         (float) : максимальная скорость (пикселей/сек)
        method        (str)   : метод преследования
        time          (float) : время моделирования (сек)
        vx, vy        (float) : текущие компоненты вектора скорости
    """

    # ------------------------------------------------------------------ #
    #  Константы — названия методов преследования
    # ------------------------------------------------------------------ #
    METHOD_APF  = "Потенциальные поля (APF)"
    METHOD_PURE = "Прямое преследование"

    # Список всех доступных методов для выпадающего списка
    METHODS = [METHOD_APF, METHOD_PURE]

    def __init__(
        self,
        x0: float,
        y0: float,
        speed: float,
        method: str = "Потенциальные поля (APF)",
        k_att: float = 2.0,
        k_rep: float = 800.0,
        d0: float = 120.0,
        d_max: float = 500.0,
    ):
        """
        Конструктор класса Pursuer.

        Параметры:
            x0, y0  : начальные координаты преследователя (пиксели)
            speed   : максимальная скорость преследователя (пикселей/сек)
            method  : метод преследования (METHOD_APF или METHOD_PURE)
            k_att   : коэффициент силы притяжения к цели
            k_rep   : коэффициент силы отталкивания от препятствий
            d0      : радиус влияния препятствий (пиксели)
            d_max   : максимальная дальность линейного притяжения (пиксели)
        """
        # ---- Начальные параметры ----
        self.x0 = x0
        self.y0 = y0
        self.x = x0
        self.y = y0
        self.speed = speed
        self.method = method
        self.time = 0.0

        # ---- Параметры метода APF ----
        self.k_att = k_att     # коэффициент притяжения
        self.k_rep = k_rep     # коэффициент отталкивания
        self.d0 = d0           # радиус влияния препятствий
        self.d_max = d_max     # максимальная дальность линейного притяжения

        # ---- Текущий вектор скорости ----
        self.vx = 0.0
        self.vy = 0.0

    # ================================================================== #
    #  Основной метод обновления позиции
    # ================================================================== #
    def update(self, dt: float, target_pos: tuple, obstacles: list):
        """
        Обновить позицию преследователя на один временной шаг.

        Параметры:
            dt         : шаг интегрирования (сек)
            target_pos : кортеж (tx, ty) — текущая позиция цели
            obstacles  : список кортежей [(ox, oy, radius), ...] — препятствия
        """
        self.time += dt

        if self.method == self.METHOD_APF:
            self._update_apf(dt, target_pos, obstacles)
        elif self.method == self.METHOD_PURE:
            self._update_pure(dt, target_pos)

    # ================================================================== #
    #  Метод APF — Artificial Potential Fields
    # ================================================================== #
    def _update_apf(self, dt: float, target_pos: tuple, obstacles: list):
        """
        Обновление позиции методом искусственных потенциальных полей.

        Алгоритм:
            1. Вычислить притягивающую силу к цели (F_att).
            2. Вычислить отталкивающие силы от каждого препятствия (F_rep_i).
            3. Просуммировать все силы: F_total = F_att + Σ F_rep_i.
            4. Нормализовать F_total и двигаться с постоянной скоростью.
            5. Если силы скомпенсированы (локальный минимум) — добавить
               небольшое возмущение для выхода.
        """
        tx, ty = target_pos

        # ================================================================ #
        #  Шаг 1: Притягивающая сила к цели
        # ================================================================ #
        # Вектор от преследователя к цели
        dx = tx - self.x
        dy = ty - self.y
        dist_to_target = math.sqrt(dx * dx + dy * dy)

        # Защита от деления на ноль (цель достигнута)
        if dist_to_target < 0.1:
            self.vx = 0.0
            self.vy = 0.0
            return

        if dist_to_target <= self.d_max:
            # Линейный притягивающий потенциал:
            #   U_att = 0.5 · k_att · ρ²
            #   F_att = k_att · (q_goal − q)
            f_att_x = self.k_att * dx
            f_att_y = self.k_att * dy
        else:
            # Конусный (ограниченный) потенциал при ρ > d_max:
            #   F_att = k_att · d_max · (q_goal − q) / ρ
            f_att_x = self.k_att * self.d_max * dx / dist_to_target
            f_att_y = self.k_att * self.d_max * dy / dist_to_target

        # ================================================================ #
        #  Шаг 2: Отталкивающие силы от препятствий
        # ================================================================ #
        f_rep_x = 0.0
        f_rep_y = 0.0

        for obs in obstacles:
            ox, oy, r_obs = obs

            # Вектор от препятствия к преследователю
            obs_dx = self.x - ox
            obs_dy = self.y - oy
            dist_to_obs = math.sqrt(obs_dx * obs_dx + obs_dy * obs_dy)

            # Эффективное расстояние с учётом радиуса препятствия
            effective_dist = max(dist_to_obs - r_obs, 1.0)

            # Отталкивание действует только если расстояние < ρ₀
            if effective_dist <= self.d0:
                # ──────────────────────────────────────────────────────── #
                #  Модифицированная отталкивающая сила (практический APF)
                # ──────────────────────────────────────────────────────── #
                #
                # Классический FIRAS: F = k·(1/ρ − 1/ρ₀)/ρ² · n̂
                #   → сила ~ 1/ρ³, ничтожно мала при ρ ≈ ρ₀.
                #
                # Наша формула:
                #   F_rep = k_rep · (1 − ρ/ρ₀) · (n̂ + α · t̂)
                #
                # 1) Линейная огибающая (1 − ρ/ρ₀):
                #    В середине зоны: F = k_rep/2 (значимая сила!)
                #    У поверхности:   F = k_rep   (максимум)
                #    На границе:      F = 0       (плавный вход)
                #
                # 2) Тангенциальная составляющая (α·t̂):
                #    t̂ перпендикулярен n̂ и направлен в сторону цели.
                #    Это создаёт «скольжение» вокруг препятствия вместо
                #    фронтального «упирания» при лобовом подходе.
                # ──────────────────────────────────────────────────────── #

                # Линейная огибающая: 1 у поверхности, 0 на границе зоны
                envelope = 1.0 - effective_dist / self.d0

                # --- Нормальная составляющая n̂ (от препятствия к пресл-лю) ---
                if dist_to_obs > 0.01:
                    n_x = obs_dx / dist_to_obs
                    n_y = obs_dy / dist_to_obs
                else:
                    # Преследователь внутри препятствия — толкаем вверх
                    n_x = 0.0
                    n_y = -1.0

                # --- Тангенциальная составляющая t̂ (скольжение вокруг) ---
                # t̂ перпендикулярен n̂; выбираем направление в сторону цели.
                t1_x, t1_y = -n_y, n_x  # один из двух вариантов
                # Вектор от преследователя к цели
                to_target_x = tx - self.x
                to_target_y = ty - self.y
                # Выбираем t̂, сонаправленный с (target − pursuer)
                if (t1_x * to_target_x + t1_y * to_target_y) >= 0:
                    t_x, t_y = t1_x, t1_y
                else:
                    t_x, t_y = n_y, -n_x

                # Коэффициент тангенциальной силы
                alpha = 0.3

                # Суммарное направление: n̂ + α·t̂, нормализованное
                dir_x = n_x + alpha * t_x
                dir_y = n_y + alpha * t_y
                dir_mag = math.sqrt(dir_x * dir_x + dir_y * dir_y)
                if dir_mag > 0.001:
                    dir_x /= dir_mag
                    dir_y /= dir_mag

                # Итоговая сила отталкивания
                magnitude = self.k_rep * envelope
                magnitude = min(magnitude, 50000.0)

                # Направление отталкивания (от препятствия к преследователю)
                if dist_to_obs > 0.01:
                    n_x = obs_dx / dist_to_obs
                    n_y = obs_dy / dist_to_obs
                else:
                    # Преследователь внутри препятствия — толкаем вверх
                    n_x = 0.0
                    n_y = -1.0

                f_rep_x += magnitude * dir_x
                f_rep_y += magnitude * dir_y

        # ================================================================ #
        #  Шаг 3: Суммарная сила
        # ================================================================ #
        total_fx = f_att_x + f_rep_x
        total_fy = f_att_y + f_rep_y

        # ================================================================ #
        #  Шаг 4: Нормализация и движение
        # ================================================================ #
        force_mag = math.sqrt(total_fx * total_fx + total_fy * total_fy)

        if force_mag > 0.01:
            # Двигаемся в направлении суммарной силы с постоянной скоростью
            self.vx = self.speed * total_fx / force_mag
            self.vy = self.speed * total_fy / force_mag
        else:
            # ============================================================ #
            #  Шаг 5: Выход из локального минимума
            # ============================================================ #
            # Силы скомпенсированы — преследователь «застрял».
            # Добавляем небольшое случайное возмущение (virtual vortex)
            # для выхода из локального минимума.
            angle_to_target = math.atan2(ty - self.y, tx - self.x)
            # Отклоняемся на ~30° от направления к цели
            perturbation_angle = angle_to_target + math.pi / 6
            self.vx = self.speed * math.cos(perturbation_angle)
            self.vy = self.speed * math.sin(perturbation_angle)

        # Обновляем позицию: q_new = q_old + v · dt
        self.x += self.vx * dt
        self.y += self.vy * dt

    # ================================================================== #
    #  Метод Pure Pursuit — Прямое преследование
    # ================================================================== #
    def _update_pure(self, dt: float, target_pos: tuple):
        """
        Прямое преследование (Pure Pursuit).

        Алгоритм:
            Преследователь всегда движется по прямой к текущей позиции
            цели с постоянной скоростью, игнорируя препятствия.

        Формула:
            direction = (target − pursuer) / ||target − pursuer||
            v = speed · direction
            q_new = q_old + v · dt
        """
        tx, ty = target_pos
        dx = tx - self.x
        dy = ty - self.y
        dist = math.sqrt(dx * dx + dy * dy)

        if dist > 0.1:
            self.vx = self.speed * dx / dist
            self.vy = self.speed * dy / dist
        else:
            self.vx = 0.0
            self.vy = 0.0

        self.x += self.vx * dt
        self.y += self.vy * dt

    # ================================================================== #
    #  Вспомогательные методы
    # ================================================================== #

    def get_current_speed(self) -> float:
        """Возвращает текущую скалярную скорость (пикселей/сек)."""
        return math.sqrt(self.vx * self.vx + self.vy * self.vy)

    def get_velocity(self) -> tuple:
        """Возвращает текущий вектор скорости (vx, vy)."""
        return self.vx, self.vy

    def get_formula(self) -> str:
        """
        Возвращает строковое описание формулы метода преследования.
        Используется для отображения в области отладочной информации.
        """
        if self.method == self.METHOD_APF:
            return (
                f"APF:  F = F_att + ΣF_rep\n"
                f"F_att = {self.k_att:.1f} · (q_goal − q),  "
                f"d_max = {self.d_max:.0f}\n"
                f"F_rep = {self.k_rep:.0f} · (1 − ρ/{self.d0:.0f}) · (n̂ + 0.3·t̂)"
            )
        else:
            return "Прямое преследование:  v = speed · (target − pos) / |target − pos|"

    def estimate_catch_time(self, target_pos: tuple, target_velocity: tuple) -> float:
        """
        Оценка времени до перехвата цели (в секундах).

        Формула:
            v_radial_target = (v_target · û) — проекция скорости цели на
                              направление «преследователь → цель»
            v_approach = speed_pursuer − v_radial_target
            t_est = distance / v_approach

        Если v_approach ≤ 0 (цель убегает быстрее) → возвращаем ∞.
        """
        tx, ty = target_pos
        tvx, tvy = target_velocity

        dx = tx - self.x
        dy = ty - self.y
        dist = math.sqrt(dx * dx + dy * dy)

        # Уже рядом — время ≈ 0
        if dist < 1.0:
            return 0.0

        # Единичный вектор от преследователя к цели: û = (dx, dy) / dist
        ux = dx / dist
        uy = dy / dist

        # Скалярное произведение скорости цели на û (радиальная составляющая)
        target_radial = tvx * ux + tvy * uy

        # Скорость сближения
        approach_speed = self.speed - target_radial

        # Если цель убегает быстрее — никогда не догоним
        if approach_speed <= 0:
            return float("inf")

        return dist / approach_speed
